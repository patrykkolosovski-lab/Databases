DROP TABLE IF EXISTS Prescription;
DROP TABLE IF EXISTS Student;
DROP TABLE IF EXISTS Doctor;
DROP TABLE IF EXISTS StudyDrug;

-- 1. Table Definitions with Constraints
CREATE TABLE Student (
    student_id INT PRIMARY KEY,
    program_name VARCHAR(100) NOT NULL,
    study_year INT NOT NULL CHECK (study_year BETWEEN 1 AND 8),
    name VARCHAR(100) NOT NULL,
    age INT NOT NULL CHECK (age BETWEEN 16 AND 100)
);

CREATE TABLE StudyDrug (
    drug_id INT PRIMARY KEY,
    drug_producer VARCHAR(100) NOT NULL,
    drug_name VARCHAR(100) NOT NULL
);

CREATE TABLE Doctor (
    doctor_id INT PRIMARY KEY,
    role VARCHAR(100) NOT NULL,
    department VARCHAR(100) NOT NULL,
    name VARCHAR(100) NOT NULL,
    age INT NOT NULL CHECK (age BETWEEN 23 AND 100)
);

CREATE TABLE Prescription (
    prescription_id INT PRIMARY KEY,
    student_id INT NOT NULL,
    drug_id INT NOT NULL,
    doctor_id INT NOT NULL,
    prescription_date DATE NOT NULL,
    dose_mg DECIMAL(6,2) NOT NULL CHECK (dose_mg > 0),
    quantity_tablets INT NOT NULL CHECK (quantity_tablets > 0),
    FOREIGN KEY (student_id) REFERENCES Student(student_id) ON DELETE RESTRICT,
    FOREIGN KEY (drug_id) REFERENCES StudyDrug(drug_id) ON DELETE RESTRICT,
    FOREIGN KEY (doctor_id) REFERENCES Doctor(doctor_id) ON DELETE RESTRICT
);

